for (const count of [500, 1000]) test(`окно назначений ${count} стыков с документами: поиск, сохранение и ограниченные запросы`, async ({ page }) => {
  const name = `FOLLOW-LOAD-${count}`, id = await seed(name, count)
  await withE2eDatabase(async db => {
    // Real document relations, not only displayed conclusion strings.
    await db.query(`insert into generated_documents(type,title,file_name,mime_type)
      select type,$1||'-'||type,$1||'-'||type||'.xlsx','application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
      from unnest(array['system:lnkRequest','system:lnkConclusionRk']) type`, [name])
    await db.query(`insert into generated_document_weld_joints(document_id,weld_joint_id)
      select d.id,w.id from generated_documents d cross join weld_joints w where d.title like $1 and w.line_program_id=$2`, [name + '-%', id])
    await db.query("update weld_joints set has_uzk=null,uzk_result=null,uzk_conclusion=null,has_pvk=null,rk_request=$2||'-system:lnkRequest',rk_conclusion=$2||'-system:lnkConclusionRk' where line_program_id=$1", [id, name])
  })
  const calls: string[] = [], errors: string[] = [], bytes: Promise<number>[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => { if (request.url().includes('/_serverFn/')) calls.push(rpcName(request.url())) })
  page.on('response', response => { if (response.url().includes('/_serverFn/') && rpcName(response.url()).startsWith('getLineProgramJointPage_')) bytes.push(response.body().then(body => body.length)) })
  const started = performance.now(), modal = await assignments(page, name)
  await expect(modal.getByTestId('line-program-joint')).toHaveCount(50)
  const openedMs = Math.round(performance.now() - started), searchAt = performance.now()
  await modal.getByLabel('Поиск стыков в назначениях').fill(`F${count}`)
  await expect(modal.getByTestId('line-program-joint')).toHaveCount(1)
  const searchMs = Math.round(performance.now() - searchAt)
  const reads = calls.filter(name => name.startsWith('getLineProgramJointPage_')).length
  const saveAt = performance.now()
  await modal.getByLabel(`F${count} · УЗК`, { exact: true }).selectOption('да')
  await modal.getByRole('button', { name: 'Проверить изменения', exact: true }).click()
  await expect(modal.getByRole('button', { name: 'Сохранить назначения', exact: true })).toBeVisible()
  const ack = modal.getByRole('checkbox', { name: /Подтверждаю назначение/ }); if (await ack.count()) await ack.check()
  await modal.getByRole('button', { name: 'Сохранить назначения', exact: true }).click()
  await expect(modal.getByText('Назначения сохранены · стыков: 1', { exact: true })).toBeVisible()
  const saveMs = Math.round(performance.now() - saveAt)
  await expect.poll(() => calls.filter(name => name.startsWith('getLineProgramJointPage_')).length).toBe(reads + 1)
  await page.evaluate(() => { window.dispatchEvent(new Event('focus')); window.dispatchEvent(new Event('online')) })
  await expect(modal.getByLabel(`F${count} · УЗК`, { exact: true })).toHaveValue('да')
  expect(calls.filter(name => name.startsWith('getLineProgramSection_'))).toHaveLength(1)
  expect(calls.filter(name => name.startsWith('getLineProgramJointPage_'))).toHaveLength(2)
  expect(calls.filter(name => name.startsWith('previewLineProgramControl_'))).toHaveLength(1)
  expect(calls.filter(name => name.startsWith('applyLineProgramControl_'))).toHaveLength(1)
  expect(errors).toEqual([])
  const responseBytes = await Promise.all(bytes)
  expect(responseBytes.every(size => size < count * 3000)).toBe(true)
  console.log(JSON.stringify({ lineSize: count, openedMs, searchMs, saveMs, detailResponseBytes: responseBytes, detailsRequests: 2 }))
})
