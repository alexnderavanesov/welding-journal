const project = 'E2E program followup'
test.afterEach(() => cleanupLineProgramProjects([project]))
async function seed(name: string, count = 2) {
  return withE2eDatabase(async db => {
    const { rows: [line] } = await db.query("insert into line_programs (project_title,subtitle_code,line,category,group_name,weld_control_percent,pvk_control_percent) values ($1,'FOLLOWUP',$2,'II','A',30,10) returning id", [project, name])
    await db.query(`insert into weld_joints (line_program_id,project_title,subtitle_code,line,joint,weld_date,connection_type,category,group_name,weld_control_percent,pvk_control_percent,has_vik,stamp_1_k,stamp_1_k_fact,has_rk,has_uzk,rk_result,rk_conclusion,uzk_result,uzk_conclusion)
      select $1,$2,'FOLLOWUP',$3,'F'||n,'2026-09-01','С17','II','A',30,10,'да','FOLLOW-K','FOLLOW-K','да','да','годен','KEEP-RK-'||n,'годен','KEEP-UZK-'||n from generate_series(1,$4::int) n`, [line.id, project, name, count])
    await db.query(`update weld_joints set officiality='действующий',revision_actuality='актуальная',welding_method='РД',material_group='M01',d1=108,d2=108,t1=4,t2=4,wdi=0.42,isometry='ISO-FOLLOW',spool='S1',vik_control_basis='проект',rk_control_basis='проект',uzk_control_basis='проект',pvk_control_basis='проект' where line_program_id=$1`, [line.id])
    if (!(await db.query("select 1 from welder_stamps where naks_stamp='FOLLOW-K'")).rowCount) await db.query(`insert into welder_stamps(naks_stamp,welder_name,weld_type,material_groups,diameter_from,diameter_to,thickness_from,thickness_to,valid_from,valid_to,naks_permits)
      values ('FOLLOW-K','E2E program followup','РД','M01','1','1000','1','100','2026-01-01','2026-12-31','[{"id":"follow","weldType":"РД","materialGroups":"M01","diameterFrom":"1","diameterTo":"1000","thicknessFrom":"1","thicknessTo":"100","validFrom":"2026-01-01","validTo":"2026-12-31","archived":false}]')`)
    return line.id as number
  })
}
async function assignments(page: Page, name: string) {
  await page.goto('/line-program')
  const program = page.getByTestId('line-program')
  await program.getByLabel('Поиск программы линий').fill(name)
  await expect(program.getByTestId('line-program-card')).toHaveCount(1)
  await program.getByTestId('line-program-header').click({ button: 'right' })
  await page.getByTestId('context-action-menu').getByRole('button', { name: 'Назначения', exact: true }).click()
  return page.getByRole('dialog', { name: `Назначения · ${name}` })
}

test('согласование старого выполненного контроля и отмена не меняют историю; отмена диалога безопасна', async ({ page }) => {
  const id = await seed('FOLLOW-APPROVAL')
  const before = await withE2eDatabase(async db => (await db.query('select * from weld_joints where line_program_id=$1 order by id', [id])).rows)
  const calls: string[] = [], errors: string[] = []
  page.on('request', request => { if (request.url().includes('/_serverFn/')) calls.push(rpcName(request.url())) })
  page.on('pageerror', error => errors.push(error.message))
  const modal = await assignments(page, 'FOLLOW-APPROVAL')
  await modal.getByLabel('Выбрать F1', { exact: true }).check()
  await modal.getByRole('button', { name: /Согласовать сочетание/ }).click()
  await page.getByRole('button', { name: 'Вернуться', exact: true }).click()
  await expect(modal.getByText('✓ Согласовано', { exact: true })).toHaveCount(0)
  await modal.getByRole('button', { name: /Согласовать сочетание/ }).click()
  await page.getByRole('button', { name: 'Согласовать', exact: true }).click()
  await expect(modal.getByText('✓ Согласовано', { exact: true })).toHaveCount(1)
  await expect(modal.getByLabel('F1 · РК', { exact: true }).locator('option[value=""]')).toBeDisabled()
  await modal.getByLabel('Выбрать F1', { exact: true }).check()
  await modal.getByLabel('Выбрать F2', { exact: true }).check()
  const mixed = modal.getByLabel('Согласование выбранных стыков')
  await expect(mixed).toBeVisible()
  expect(await mixed.evaluate(el => { const css = getComputedStyle(el); return parseFloat(css.lineHeight) + parseFloat(css.paddingTop) + parseFloat(css.paddingBottom) <= el.clientHeight })).toBe(true)
  await modal.screenshot({ path: 'outputs/program-approval-selection.png' })
  await mixed.selectOption('revoke:combination')
  await page.getByRole('button', { name: 'Снять согласование', exact: true }).click()
  await expect(modal.getByText('✓ Согласовано', { exact: true })).toHaveCount(0)
  await expect(modal.getByLabel('F1 · РК', { exact: true })).toHaveValue('да')
  await expect(modal.getByLabel('F1 · РК', { exact: true }).locator('option[value=""]')).toBeDisabled()
  await withE2eDatabase(async db => {
    expect((await db.query('select * from weld_joints where line_program_id=$1 order by id', [id])).rows).toEqual(before)
    expect((await db.query('select key from dispatcher_accepted_warnings where weld_joint_id=any($1::int[])', [before.map(row => row.id)])).rows).toEqual([])
  })
  expect(calls.filter(name => name.startsWith('changeLineProgramApprovals_'))).toHaveLength(2)
  expect(calls.filter(name => name.startsWith('getLineProgramSection_'))).toHaveLength(1)
  expect(calls.filter(name => name.startsWith('getLineProgramJointPage_'))).toHaveLength(3)
  expect(errors).toEqual([])
  await modal.screenshot({ path: 'outputs/program-approval-actions.png' })
})

