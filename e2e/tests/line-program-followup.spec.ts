  await expect(cardHeader.getByRole('button', { name: 'ПВК · зачтено / нужно 1 / 2', exact: true })).toBeVisible()
  await expect(cardHeader.getByRole('button', { name: 'К назначению 3', exact: true })).toBeVisible()
  const header = program.getByRole('button', { name: `Расчёт линии ${name}`, exact: true })
  if (await header.getAttribute('aria-expanded') !== 'true') await header.click()
  const all = program.getByRole('button', { name: 'Все стыки линии', exact: true })
