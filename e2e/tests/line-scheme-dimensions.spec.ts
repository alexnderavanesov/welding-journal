  await dialog.getByLabel('Показывать размеры', { exact: true }).uncheck()
  await expect(dimension).toHaveCount(0)
  await expect(dialog.getByRole('button', { name: /^Размер S/ })).toHaveCount(1)
  await expect(dialog.getByRole('button', { name: /^Сохранить/ })).toBeDisabled()
