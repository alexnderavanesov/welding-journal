  await dialog.getByRole('button', { name: 'Добавить расстояние' }).click(); await point(1).click(); await point(3).click()
  await dimensionDialog.getByLabel('Расстояние, мм', { exact: true }).fill('300'); await page.keyboard.press('Enter'); await save()
  await point(1).click(); await page.keyboard.press('Delete'); await save()
  await dialog.getByRole('button', { name: 'Закрыть схему', exact: true }).click()
  await page.getByRole('row').filter({ hasText: project }).getByRole('button', { name: 'Dimensions', exact: true }).click()
