  const labelHeight = (await dimension.boundingBox())!.height
  expect(labelHeight).toBeLessThan(30)
  await dialog.getByRole('button', { name: 'Повернуть', exact: true }).click()
  await dialog.getByRole('button', { name: 'Повернуть', exact: true }).click()
  await dialog.getByRole('button', { name: 'Повернуть', exact: true }).click()
