  // is the physical Mac shortcut. Exercise the Ctrl click handler separately.
  if (await page.evaluate(() => navigator.platform.startsWith('Mac'))) await point(2).dispatchEvent('click', { ctrlKey: true })
  else await point(2).click({ modifiers: ['Control'] })
  await expect(dialog.locator('[data-scheme-point][aria-pressed="true"]')).toHaveCount(2)
