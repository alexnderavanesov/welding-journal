  expect(await withE2eDatabase(async db => (await db.query('select (select count(*)::int from line_scheme_points where revision_id=$1) as points, (select count(*)::int from line_scheme_dimensions where revision_id=$1) as dimensions', [firstId])).rows[0])).toEqual({ points: 0, dimensions: 0 })
