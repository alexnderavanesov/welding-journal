import { expect, test } from '@playwright/test'

test('calculation guide supports direct links, all tabs, examples and narrow screens', async ({ page }, info) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/account?tab=rules&section=assignments')
  const navigation = page.getByRole('tablist', { name: 'Разделы правил системы', exact: true })
  const assignments = navigation.getByRole('tab', { name: 'Назначения и расчёты', exact: true })
  await expect(assignments).toHaveAttribute('aria-selected', 'true')
  const panel = page.getByRole('tabpanel', { name: 'Назначения и расчёты', exact: true })
  await expect(panel.getByRole('heading', { level: 3 })).toHaveCount(12)
  await expect(panel.getByRole('button', { name: /Сохранить/ })).toHaveCount(0)
  await expect(panel.getByRole('cell', { name: '3 + 6 = 9', exact: true })).toBeAttached()
  await page.screenshot({ path: info.outputPath('calculation-guide-wide.png') })
  await assignments.focus()
  await page.keyboard.press('ArrowRight')
  await expect(navigation.getByRole('tab', { name: 'Соединения', exact: true })).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(assignments).toBeFocused()
  await navigation.getByRole('tab', { name: 'Параметры проверки', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Как проверяется допуск клейма', exact: true })).toBeVisible()
  await page.goBack()
  await expect(assignments).toHaveAttribute('aria-selected', 'true')
  await page.reload()
  await expect(assignments).toHaveAttribute('aria-selected', 'true')
  await page.setViewportSize({ width: 680, height: 1000 })
  await panel.getByRole('link', { name: '10. Опоры Т: отдельные нормы УЗК и ПВК', exact: true }).click()
  await expect(panel.getByRole('heading', { name: '10. Опоры Т: отдельные нормы УЗК и ПВК', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true)
  await page.screenshot({ path: info.outputPath('calculation-guide-narrow.png') })
  expect(errors).toEqual([])
})
