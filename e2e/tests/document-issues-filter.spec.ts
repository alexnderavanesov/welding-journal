import { expect, test } from '@playwright/test'
import { cleanupLineProgramProjects, withLineProgramFixture } from '../line-program-fixtures'

const project = 'E2E document issues help'
test.afterEach(() => cleanupLineProgramProjects([project]))

test('issue help explains the filter without changing it; keyboard filtering preserves selected joints', async ({ page }) => {
  await withLineProgramFixture(db => db.query(`insert into weld_joints(project_title,subtitle_code,line,joint,weld_date,connection_type,officiality,revision_actuality,has_vik,psto_required)
    select $1,case when n=1 then '' else 'HELP' end,'HELP-CHECK-L'||n,'F9750'||n,'2026-10-01','С17','действующий','актуальная','да','нет' from generate_series(1,2)n`, [project]))
  await page.goto('/lnk')
  await page.locator('header').getByRole('button', { name: 'Заявка', exact: true }).click()
  await page.getByRole('button', { name: 'Новая заявка', exact: true }).click()
  const dialog = page.getByRole('dialog').filter({ has: page.getByRole('heading', { name: 'Заявка ЛНК', exact: true }) })
  const method = dialog.getByRole('button', { name: 'ВИК', exact: true })
  if (await method.getAttribute('aria-pressed') !== 'true') await method.click()
  await dialog.getByPlaceholder('Проект, шифр, линия, спул или стык').fill('HELP-CHECK-L')
  const checks = dialog.getByRole('checkbox', { name: /^Выбрать стык HELP-CHECK-L/ })
  await expect(checks).toHaveCount(2)
  await checks.first().focus()
  await page.keyboard.press('Space')
  await expect(checks.first()).toBeChecked()
  await checks.last().check()
  await dialog.getByRole('combobox', { name: 'Разделение документов', exact: true }).selectOption('line')
  await dialog.getByRole('tab', { name: /^Заявки и имена/ }).click()
  const filter = dialog.getByRole('checkbox', { name: /^Только проблемные группы/ })
  await expect(filter).not.toBeChecked()
  await dialog.getByRole('button', { name: 'Что значит «Только проблемные группы»', exact: true }).click()
  await expect(page.getByRole('tooltip')).toContainText('Каждая группа — стыки, которые войдут в один документ.')
  await expect(page.getByRole('tooltip')).toContainText('Фильтр ничего не удаляет и не меняет выбор стыков.')
  await expect(filter).not.toBeChecked()
  await dialog.screenshot({ path: 'outputs/document-issues-help.png' })
  await page.keyboard.press('Escape')
  await expect(page.getByRole('tooltip')).toBeHidden()
  await expect(dialog).toBeVisible()
  const names = dialog.getByRole('textbox', { name: /^Название/ })
  await expect(names).toHaveCount(2)
  await filter.focus()
  await page.keyboard.press('Space')
  await expect(filter).toBeChecked()
  await expect(names).toHaveCount(1)
  await page.keyboard.press('Space')
  await expect(names).toHaveCount(2)
  await dialog.getByRole('tab', { name: 'Стыки', exact: true }).click()
  await expect(dialog.getByRole('button', { name: 'Выбрано: 2', exact: true })).toBeVisible()
  for (const checkbox of await checks.all()) await expect(checkbox).toBeChecked()
})
