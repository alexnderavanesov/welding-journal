  await expect(dot(page, 'Системные индексы')).toHaveCount(0)

  await page.getByRole('button', { name: 'Заявки и заключения', exact: true }).click()
  const namesBefore = await read('request-conclusion')
  await page.getByRole('button', { name: 'Раскрыть', exact: true }).first().click()
