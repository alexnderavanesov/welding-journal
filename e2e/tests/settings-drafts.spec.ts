  await page.getByRole('button', { name: 'Системные индексы', exact: true }).click()
  const indexBefore = await read('system-index')
  await page.getByRole('checkbox', { name: /Разрешать буквенный индекс перед номером стыка/ }).click()
  await expect(dot(page, 'Системные индексы')).toBeVisible()
  expect(await read('system-index')).toBe(indexBefore)
