test('назначения опор сохраняют независимую норму, отдельный Доп и безопасное снятие без согласований С/У', async ({ page }) => {
  const id = await seed(false, 5)
  await page.setViewportSize({ width: 1800, height: 1050 })
  const ordinary = () => withE2eDatabase(async db => (await db.query(`select joint,has_vik,has_rk,has_uzk,has_pvk,vik_result,rk_result,uzk_result,pvk_result
    from weld_joints where line_program_id=$1 and connection_type='С17' order by joint`, [id])).rows)
  const ordinaryBefore = await ordinary()
  const assignments = () => withE2eDatabase(async db => Object.fromEntries((await db.query(`select joint,coalesce(has_uzk,'') as value
    from weld_joints where line_program_id=$1 and joint=any($2::text[]) order by joint`, [id, ['ОП1', 'ОП2', 'ОП3', 'ОП4', 'ОП5']])).rows.map(row => [row.joint, row.value])))
  const approvals = () => withE2eDatabase(async db => (await db.query(`select key from dispatcher_accepted_warnings
    where line_program_id=$1 or weld_joint_id in (select id from weld_joints where line_program_id=$1)`, [id])).rows)
  const program = await open(page)
  const card = program.getByTestId('line-program-card')
  const excess = card.locator('[data-line-metric][data-program-slice="excess"]')
  await expect(card.locator('[data-line-metric][data-program-kind="common"]')).toHaveAttribute('aria-label', 'УЗК · зачтено / нужно 0 / 3')
  const editor = page.getByRole('dialog', { name: `Назначения · ${TARGET}`, exact: true })
  const openAssignments = async () => {
    await card.getByRole('button', { name: `Открыть назначения линии ${TARGET}`, exact: true }).click()
    await expect(editor.getByLabel('Поиск стыков в назначениях')).toBeVisible()
  }
  const setUzk = async (joint: string, value: string) => {
    await editor.getByLabel('Поиск стыков в назначениях').fill(joint)
    await editor.getByRole('combobox', { name: `${joint} · УЗК`, exact: true }).selectOption(value)
    if (value === 'дополнительный' || value === 'отменен') {
      await expect(editor.getByRole('button', { name: 'Проверить изменения', exact: true })).toBeDisabled()
      const basis = editor.getByLabel(`${joint} · УЗК · Основание к назначению`, { exact: true })
      await basis.pressSequentially('ТР № 10')
      await expect(basis).toHaveValue('ТР № 10')
      await expect(basis).toBeFocused()
    }
    await editor.getByRole('button', { name: 'Очистить поиск стыков', exact: true }).click()
  }
  const save = async (changed: number, expectedExcess: number) => {
    await editor.getByRole('button', { name: 'Проверить изменения', exact: true }).click()
    const submit = editor.getByRole('button', { name: 'Сохранить назначения', exact: true })
    await expect(submit).toBeEnabled()
    await expect(editor.getByRole('checkbox', { name: /Подтверждаю назначение сверх нормы/ })).toHaveCount(0)
    if (changed === 4) await editor.screenshot({ path: 'outputs/t-op-assignments-overquota.png' })
    await submit.click()
    await expect(submit).toHaveCount(0)
    await expect(editor.getByText(`Назначения сохранены · стыков: ${changed}`, { exact: true })).toBeVisible()
    await editor.getByRole('button', { name: 'Вернуться к просмотру', exact: true }).click()
    await expect(editor).toHaveCount(0)
    await expect(excess).toHaveAttribute('aria-label', `Лишнее ${expectedExcess}`)
    expect(await approvals()).toEqual([])
  }

  await openAssignments()
  await expect(editor.getByTestId('assignment-guidance-common')).toContainText('УЗК · по клеймам')
  await expect(editor.getByTestId('assignment-guidance-common')).toContainText('К назначению: 3')
  await expect(editor.getByRole('button', { name: 'РК', exact: true })).toHaveCount(0)
  for (const joint of ['ОП1', 'ОП2', 'ОП3', 'ОП4']) await setUzk(joint, 'да')
  await save(4, 1)
  expect(await assignments()).toEqual({ ОП1: 'да', ОП2: 'да', ОП3: 'да', ОП4: 'да', ОП5: '' })

  await openAssignments()
  await setUzk('ОП4', 'дополнительный')
  await save(1, 0)
  expect(await assignments()).toEqual({ ОП1: 'да', ОП2: 'да', ОП3: 'да', ОП4: 'дополнительный', ОП5: '' })

  await openAssignments()
  await expect(editor.getByLabel('ОП4 · УЗК · Основание к назначению', { exact: true })).toHaveValue('ТР № 10')
  await setUzk('ОП5', 'да')
  await save(1, 1)
  const beforeRemoval = await assignments()
  await openAssignments()
  // Selection is only a proposal. The current fifth ordinary assignment is removable;
  // the explicitly accepted Additional assignment is never included in this proposal.
  const candidates = editor.getByRole('button', { name: 'Выделить кандидатов на снятие', exact: true })
  await expect(candidates).toContainText('Кандидаты на снятие: 1')
  await candidates.click()
  await editor.getByLabel('Поиск стыков в назначениях').fill('ОП5')
  await expect(editor.getByRole('checkbox', { name: 'Выбрать ОП5', exact: true })).toBeChecked()
  await expect(editor.getByRole('combobox', { name: 'ОП5 · УЗК', exact: true })).toHaveValue('да')
  expect(await assignments()).toEqual(beforeRemoval)
  await editor.getByRole('button', { name: 'УЗК', exact: true }).click()
  await editor.getByRole('radio', { name: 'Пусто', exact: true }).click()
  const apply = editor.getByRole('button', { name: 'Применить к выбранным (1)', exact: true })
  await apply.click()
  await expect(editor.getByRole('combobox', { name: 'ОП5 · УЗК', exact: true })).toHaveValue('')
  expect(await assignments()).toEqual(beforeRemoval)
  await editor.getByRole('button', { name: 'Отменить изменения', exact: true }).click()
  await page.getByRole('dialog', { name: 'Отменить изменения назначений?', exact: true }).getByRole('button', { name: 'Отменить изменения', exact: true }).click()
  await expect(editor.getByRole('combobox', { name: 'ОП5 · УЗК', exact: true })).toHaveValue('да')
  expect(await assignments()).toEqual(beforeRemoval)
  await apply.click()
  await save(1, 0)
  expect(await assignments()).toEqual({ ОП1: 'да', ОП2: 'да', ОП3: 'да', ОП4: 'дополнительный', ОП5: '' })
  expect(await ordinary()).toEqual(ordinaryBefore)
  await program.getByRole('button', { name: 'Процентные линии', exact: true }).click()
  await expect(card.locator('[data-line-metric][data-program-kind="common"]')).toHaveAttribute('aria-label', 'РК - УЗК · зачтено / нужно 0 / 1')
  expect(await withE2eDatabase(async db => (await db.query(`select weld_control_percent,pvk_control_percent,support_uzk_control_percent,support_pvk_control_percent
    from line_programs where id=$1`, [id])).rows[0])).toMatchObject({ weld_control_percent: '30.000', pvk_control_percent: '10.000', support_uzk_control_percent: '5.000', support_pvk_control_percent: '0.500' })
})

