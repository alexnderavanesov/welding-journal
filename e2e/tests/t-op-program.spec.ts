const PROJECT = 'E2E T-OP program'
const TARGET = 'T-OP-060'
test.afterEach(() => cleanupLineProgramProjects([PROJECT]))

async function seed(extraLines = false, supportUzkPercent = 100) {
  return withLineProgramFixture(async db => {
    const { rows: [line] } = await db.query(`insert into line_programs(project_title,subtitle_code,line,category,group_name,weld_control_percent,pvk_control_percent,support_uzk_control_percent,support_pvk_control_percent)
      values($1,'SUPPORT',$2,'II','A',30,10,$3,0.5) returning id`, [PROJECT, TARGET, supportUzkPercent])
    await db.query(`insert into weld_joints(line_program_id,project_title,subtitle_code,line,joint,connection_type,weld_date,weld_length,category,group_name,weld_control_percent,pvk_control_percent,has_vik,stamp_1_k,officiality,revision_actuality)
      select $1,$2,'SUPPORT',$3,'ОП'||n,'Т1','2026-09-01',600.123456789,'II','A',30,10,'да','SUPPORT-A','действующий','актуальная' from generate_series(1,60) n`, [line.id, PROJECT, TARGET])
    await db.query(`insert into weld_joints(line_program_id,project_title,subtitle_code,line,joint,connection_type,weld_date,category,group_name,weld_control_percent,pvk_control_percent,has_vik,stamp_1_k,officiality,revision_actuality)
      select $1,$2,'SUPPORT',$3,'F'||n,'С17','2026-09-01','II','A',30,10,'да','WELD-A','действующий','актуальная' from generate_series(1,4) n`, [line.id, PROJECT, TARGET])
    if (extraLines) {
      await db.query(`insert into line_programs(project_title,subtitle_code,line,category,group_name,weld_control_percent,pvk_control_percent)
        select $1,'SUPPORT','T-OP-'||lpad(n::text,3,'0'),'II','A',30,10 from generate_series(0,59) n`, [PROJECT])
      // Every line in this pagination fixture must actually belong to Supports.
      await db.query(`insert into weld_joints(line_program_id,project_title,subtitle_code,line,joint,connection_type)
        select id,project_title,subtitle_code,line,'ОП-план','Т1' from line_programs where project_title=$1 and line<>$2`, [PROJECT, TARGET])
    }
    return line.id as number
  })
}
async function open(page: Page, search = TARGET) {
  await page.goto('/line-program')
  const program = page.getByTestId('line-program')
  await program.getByRole('button', { name: 'Опоры', exact: true }).click()
  await program.getByLabel('Поиск программы линий').fill(search)
  if (search === TARGET) await expect(program.getByRole('button', { name: `Расчёт линии ${TARGET}`, exact: true })).toBeVisible()
  else await expect(program.getByTestId('line-program-card').first()).toBeVisible()
  return program
}

