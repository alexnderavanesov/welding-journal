import { expect, test } from '@playwright/test'
import { resetE2eAccountFixtureLimits, latestE2eToken } from '../authentication'
import { withE2eDatabase } from '../database'

test.beforeEach(resetE2eAccountFixtureLimits)

test('guest is closed; alternate account APIs and Excel do not bypass access', async ({ browser, baseURL }) => {
  const context = await browser.newContext({ baseURL, storageState: { cookies: [], origins: [] } })
  try {
    const page = await context.newPage(); await page.goto('/journal')
    await expect(page.getByRole('heading', { name: 'Вход в систему' })).toBeVisible()
    await page.screenshot({ path: '/private/tmp/welding-auth-login.png', fullPage: true })
    await expect(page.getByText('E2E проект', { exact: true })).toHaveCount(0)
    const response = await context.request.post('/api/report-excel', { data: { report: 'weldingJournal' } })
    expect(response.ok()).toBe(false)
    for (const endpoint of ['sign-up/email', 'change-email', 'update-user', 'request-password-reset']) expect((await context.request.post(`/api/auth/${endpoint}`, { data: {} })).status()).toBe(404)
  } finally { await context.close() }
})
test('owner invites, user activates, immutable email, recovery revokes old sessions, then account deletion', async ({ page, browser, baseURL }) => {
  await page.goto('/account')
  await page.getByRole('tab', { name: 'Пользователи и права', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Пользователи и права' })).toBeVisible()
  await page.getByRole('button', { name: 'Пригласить пользователя', exact: true }).click()
  await page.getByRole('textbox', { name: 'ФИО', exact: true }).last().fill('Читатель E2E')
  await page.getByRole('textbox', { name: 'Почта', exact: true }).last().fill('reader@e2e.test')
  await page.screenshot({ path: '/private/tmp/welding-auth-permissions.png', fullPage: true })
  await page.getByRole('button', { name: 'Создать и отправить приглашение', exact: true }).click()
  await expect(page.getByText('reader@e2e.test', { exact: true })).toBeVisible()
  const token = await latestE2eToken()
  const context = await browser.newContext({ baseURL, storageState: { cookies: [], origins: [] } })
  try {
    const user = await context.newPage(); await user.goto(`/account-link#token=${token}&kind=invite`)
    await user.getByLabel('Новый пароль', { exact: true }).fill('reader123')
    await user.getByLabel('Повторите пароль').fill('reader123')
    await user.getByRole('button', { name: 'Сохранить пароль', exact: true }).click()
    await expect(user.getByRole('heading', { name: 'Пароль сохранён' })).toBeVisible()
    await user.getByRole('link', { name: 'Перейти ко входу' }).click()
    await user.getByLabel('Почта', { exact: true }).fill('reader@e2e.test')
    await user.getByLabel('Пароль', { exact: true }).fill('reader123')
    await user.getByRole('button', { name: 'Войти', exact: true }).click()
    await expect(user.getByRole('heading', { name: 'Мой профиль' })).toBeVisible()
    await expect(user.getByLabel('Почта', { exact: true })).toHaveAttribute('readonly', '')
    await expect(user.getByRole('heading', { name: 'Пользователи и права' })).toHaveCount(0)
    await user.goto('/activity'); await expect(user.getByText('Доступ к истории не предоставлен администратором.')).toBeVisible()
    await page.getByRole('button', { name: 'Обновить список', exact: true }).click()
    await expect(page.getByRole('row').filter({ hasText: 'reader@e2e.test' })).toContainText('Активирован')
    const row = page.getByRole('row').filter({ hasText: 'reader@e2e.test' })
    await row.getByRole('button', { name: 'Восстановить доступ', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Отправить ссылку', exact: true }).click()
    await expect(page.getByRole('dialog')).toHaveCount(0)
    const recoveryToken = await latestE2eToken()
    const recovery = await context.newPage()
    await recovery.goto(`/account-link#token=${recoveryToken}&kind=recovery`)
    await expect(recovery.getByRole('heading', { name: 'Восстановление доступа' })).toBeVisible()
    await recovery.getByLabel('Новый пароль', { exact: true }).fill('recovered123')
    await recovery.getByLabel('Повторите пароль').fill('recovered123')
    await recovery.getByRole('button', { name: 'Сохранить пароль', exact: true }).click()
    await expect(recovery.getByRole('heading', { name: 'Пароль сохранён' })).toBeVisible()
    await user.bringToFront()
    await user.evaluate(() => window.dispatchEvent(new Event('focus')))
    await expect(user.getByRole('heading', { name: 'Вход в систему' })).toBeVisible()
    await user.getByLabel('Почта', { exact: true }).fill('reader@e2e.test')
    await user.getByLabel('Пароль', { exact: true }).fill('reader123')
    await user.getByRole('button', { name: 'Войти', exact: true }).click()
    await expect(user.getByText(/Не удалось войти/)).toBeVisible()
    await user.getByLabel('Пароль', { exact: true }).fill('recovered123')
    await user.getByRole('button', { name: 'Войти', exact: true }).click()
    await expect(user.getByText('Доступ к истории не предоставлен администратором.')).toBeVisible()
    await page.getByRole('button', { name: 'Обновить список', exact: true }).click()
    await row.getByRole('button', { name: 'Удалить', exact: true }).click()
    await page.getByRole('dialog').getByRole('button', { name: 'Удалить пользователя', exact: true }).click()
    await expect(page.getByText('reader@e2e.test', { exact: true })).toHaveCount(0)
    await user.reload(); await expect(user.getByRole('heading', { name: 'Вход в систему' })).toBeVisible()
    const count = await withE2eDatabase(async client => (await client.query("select count(*)::int as count from audit_operations where actor_name='Читатель E2E'")).rows[0].count)
    expect(count).toBeGreaterThan(0)
  } finally { await context.close() }
})
