import { expect, test, type Page } from '@playwright/test'
import { cleanupLineProgramProjects, withLineProgramFixture } from '../line-program-fixtures'
const project = 'E2E program view settings', line = 'VIEW-01'
test.afterEach(() => cleanupLineProgramProjects([project]))
test.beforeEach(async ({ page }) => {
  await withLineProgramFixture(async db => {
    const { rows: [program] } = await db.query(`insert into line_programs(project_title,subtitle_code,line,category,group_name,weld_control_percent,pvk_control_percent)
      values ($1,'VIEW',$2,'II','A',100,100) returning id`, [project, line])
    await db.query(`insert into weld_joints(line_program_id,project_title,subtitle_code,line,joint,weld_date,officiality,revision_actuality,connection_type,stamp_1_k,stamp_1_z,has_vik,vik_result)
      select $1,$2,'VIEW',$3,'F'||n,'2026-09-01','действующий','актуальная','С17','VIEW-A','VIEW-B','да','годен' from generate_series(1,5) n`, [program.id, project, line])
  })
  await page.goto('/line-program')
  await expect(page.getByLabel('Итоги раздела')).toBeVisible()
  await page.getByLabel('Поиск программы линий').fill(line)
  await expect(page.getByTestId('line-program-card')).toHaveCount(1)
})
const panel = (page: Page) => page.getByRole('dialog', { name: 'Вид программы линий', exact: true })
const settings = (page: Page) => page.getByRole('button', { name: 'Настроить вид программы линий', exact: true })
const overview = (page: Page) => page.locator('[data-program-grid="lines"]')

test('cold reload pointer disclosure has no cell frame; keyboard still has a focus cue', async ({ page }) => {
  for (let attempt = 0; attempt < 3; attempt++) {
    await page.reload()
    const card = page.getByTestId('line-program-card').filter({ hasText: line })
    const cell = card.locator('.ag-cell[col-id="stamps"]')
    await cell.click()
    await expect(card.getByRole('button', { name: `Расчёт линии ${line}`, exact: true })).toHaveAttribute('aria-expanded', 'true')
    await expect(cell).toHaveCSS('box-shadow', 'none')
    await expect(cell).toHaveCSS('border-top-color', 'rgba(0, 0, 0, 0)')
    await cell.press('ArrowRight')
    await expect(page.locator('html')).toHaveAttribute('data-program-keyboard', 'true')
    await expect(overview(page).locator('.ag-cell:focus')).not.toHaveCSS('box-shadow', 'none')
    await cell.click()
    await expect(cell).toHaveCSS('box-shadow', 'none')
    await expect(page.locator('html')).not.toHaveAttribute('data-program-keyboard', 'true')
  }
})

test('appearance updates all live tables, preserves the assignment draft and persists separately', async ({ page }) => {
  await page.getByRole('button', { name: `Расчёт линии ${line}`, exact: true }).click()
  await page.getByRole('button', { name: 'Все стыки линии', exact: true }).click()
  await page.getByRole('button', { name: 'Назначения линии', exact: true }).click()
  const editor = page.getByRole('dialog', { name: `Назначения · ${line}`, exact: true })
  await editor.getByRole('combobox', { name: 'F2 · РК', exact: true }).selectOption('да')
  await editor.getByRole('button', { name: 'Вернуться к просмотру', exact: true }).click()
  const all = page.getByTestId('line-program-all-joints')
  await all.getByRole('columnheader', { name: 'Стык', exact: true }).locator('.ag-header-cell-filter-button').click()
  const filter = page.locator('.ag-filter').filter({ visible: true })
  await filter.getByRole('checkbox', { name: 'Выбрать все', exact: true }).uncheck()
  await filter.getByRole('checkbox', { name: 'F2', exact: true }).check()
  await filter.getByRole('button', { name: 'Применить', exact: true }).click()
  await expect(all.getByTestId('line-program-readonly-joint')).toHaveCount(1)
  const row = page.getByTestId('line-program-readonly-joint').filter({ hasText: 'F2' })
  const before = await row.boundingBox()
  await settings(page).click()
  await panel(page).getByRole('tab', { name: 'Оформление', exact: true }).click()
  await panel(page).getByRole('combobox', { name: 'Плотность таблиц' }).click()
  await panel(page).getByRole('option', { name: /Просторно/ }).click()
  await expect.poll(async () => (await row.boundingBox())!.height).toBeGreaterThan(before!.height)
  await panel(page).getByRole('switch', { name: 'Вертикальные границы', exact: true }).check()
  await panel(page).getByRole('tab', { name: 'Темы', exact: true }).click()
  await expect(panel(page).getByRole('tab', { name: 'Темы', exact: true })).toBeFocused()
  await panel(page).getByRole('radio', { name: /Нейтральная/ }).click()
  await panel(page).screenshot({ path: '/private/tmp/ag-grid-refinements-20261019/program-settings-theme.png' })
  await expect(overview(page)).toHaveAttribute('data-program-theme', 'balham')
  await expect(page.locator('[data-program-grid="joints"]')).toHaveAttribute('data-program-density', 'spacious')
  await expect(all.getByTestId('line-program-readonly-joint')).toHaveCount(1)
  await expect(all.getByRole('button', { name: 'F2', exact: true })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(panel(page)).toBeHidden()
  await expect(settings(page)).toBeFocused()
  await page.getByRole('button', { name: /Назначения линии/, exact: false }).filter({ hasText: /Назначения линии/ }).click()
  await expect(editor.getByRole('combobox', { name: 'F2 · РК', exact: true })).toHaveValue('да')
  await expect(editor.locator('[data-program-grid="assignments"]')).toHaveAttribute('data-program-theme', 'balham')
  await editor.getByRole('button', { name: 'Вернуться к просмотру', exact: true }).click()
  // Appearance persistence is independent of the explicitly discarded in-memory draft.
  page.once('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(overview(page)).toHaveAttribute('data-program-theme', 'balham')
  await expect(overview(page)).toHaveAttribute('data-program-density', 'spacious')
  await settings(page).click()
  await panel(page).getByRole('tab', { name: 'Оформление', exact: true }).click()
  await panel(page).getByRole('button', { name: 'Вернуть исходное оформление', exact: true }).click()
  await expect(overview(page)).toHaveAttribute('data-program-theme', 'quartz')
  await expect(overview(page)).toHaveAttribute('data-program-density', 'comfortable')
})

