function normalizeRuleReference(value: string) {
  return value.trim().toLocaleLowerCase('ru-RU').replace(/[\s-]/g, '')
}

export function getSystemRule(reference: string): SystemRuleCatalogEntry | undefined {
  const normalized = normalizeRuleReference(reference)
  return SYSTEM_RULE_CATALOG.find((rule) => [rule.code, rule.title, ...rule.aliases]
    .some((alias) => normalizeRuleReference(alias) === normalized))
}

export function getSystemRuleTargetId(code: SystemRuleCode) {
  return `system-rule-${RULE_ANCHORS[code]}`
}

export function getSystemRuleSettingsHref(reference: string) {
  const rule = getSystemRule(reference)
  return rule ? `/settings#${getSystemRuleTargetId(rule.code)}` : undefined
}

export function resolveSystemRuleSettingsHash(hash: string) {
  let reference: string
  try {
    reference = decodeURIComponent(hash.replace(/^#/, ''))
  } catch {
    return undefined
  }
  return (LEGACY_RULE_ANCHORS[reference] ? getSystemRule(LEGACY_RULE_ANCHORS[reference]) : undefined)
    ?? getSystemRule(Object.entries(LEGACY_SETTING_ANCHORS).find(([, anchors]) => anchors.includes(reference))?.[0] ?? '')
    ?? SYSTEM_RULE_CATALOG.find((rule) => getSystemRuleTargetId(rule.code) === reference)
    ?? getSystemRule(reference.replace(/^(save-check-setting-|dispatcher-setting-)/, ''))
}
