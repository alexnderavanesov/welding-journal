export function connectionRuleSpan(row: ConnectionRule | undefined, column: 'c' | 'u' | 't', pending = SUPPORT_CONNECTION_RULES_PENDING, displayedColumns: readonly string[] = ['c', 'u', 't']): number {
  const start = displayedColumns.indexOf(column)
  if (!row || start < 0 || pending && column === 't') return 1
  let span = 1
  // Only adjacent visible family columns in the same pinned area may merge.
  // Hiding or pinning У must never cover a different Т value with the С text.
  for (const next of displayedColumns.slice(start + 1)) {
    if (next !== 'c' && next !== 'u' && next !== 't' || pending && next === 't' || row[next] !== row[column]) break
    span++
  }
  return span
}
